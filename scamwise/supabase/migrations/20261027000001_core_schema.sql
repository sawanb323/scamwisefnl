-- device bound to the caller's current session, only if ACTIVE
create or replace function public.current_device_id()
returns uuid language sql stable security definer set search_path = '' as $$
  select d.id from public.devices d
  where d.user_id = auth.uid()
    and d.session_id = public.jwt_session_id()
    and d.status = 'active'
  limit 1
$$;

-- admin = listed in admin_users AND signed in with MFA (aal2). Phone number never counts.
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.admin_users a where a.user_id = auth.uid())
     and coalesce(auth.jwt() ->> 'aal', 'aal1') = 'aal2'
$$;

-- profiles: owner (from an active device) can read; can update preference columns only
create policy profiles_select on public.profiles for select to authenticated
  using (id = auth.uid() and public.current_device_id() is not null);
create policy profiles_update on public.profiles for update to authenticated
  using (id = auth.uid() and public.current_device_id() is not null)
  with check (id = auth.uid());
revoke update on public.profiles from authenticated, anon;
grant update (share_with_admin, share_excerpt, notify_high, notify_medium, retention_days)
  on public.profiles to authenticated;

-- devices: active device sees all of the account's devices; a pending device sees only itself
create policy devices_select on public.devices for select to authenticated
  using (user_id = auth.uid()
         and (public.current_device_id() is not null or session_id = public.jwt_session_id()));

-- pairing codes (no secrets in this table): visible to the account's active devices,
-- and to the device that claimed it
create policy pairing_select on public.pairing_codes for select to authenticated
  using (user_id = auth.uid()
         and (public.current_device_id() is not null
              or claimed_by_device in (select id from public.devices where session_id = public.jwt_session_id())));

-- incidents: account owner from an active device
create policy incidents_select on public.incidents for select to authenticated
  using (user_id = auth.uid() and public.current_device_id() is not null);
create policy incidents_delete on public.incidents for delete to authenticated
  using (user_id = auth.uid() and public.current_device_id() is not null);

-- alerts: only the device they were addressed to, and only while it is active
create policy alerts_select on public.alerts for select to authenticated
  using (target_device_id = public.current_device_id());

-- feedback: anyone may submit; nobody may read through the API (admins use an RPC)
create policy feedback_insert on public.feedback for insert to anon, authenticated
  with check (true);

-- pairing_secrets, pairing_attempts, admin_users, audit_log: no policies => no client access

-- tighten default grants
revoke all on public.pairing_secrets, public.pairing_attempts, public.admin_users, public.audit_log
  from anon, authenticated;
revoke insert, update on public.devices, public.pairing_codes, public.incidents, public.alerts
  from anon, authenticated;
revoke all on public.profiles, public.devices, public.pairing_codes, public.incidents, public.alerts from anon;
revoke select, update, delete on public.feedback from anon, authenticated;
grant insert on public.feedback to anon, authenticated;
grant usage, select on sequence public.feedback_id_seq to anon, authenticated;

-- ---------------------------------------------------------------- profile bootstrap
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, phone_masked)
  values (new.id, public.mask_phone(new.phone))
  on conflict (id) do nothing;
  return new;
end $$;

create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------------------------------------------------------------- realtime
alter publication supabase_realtime add table public.alerts, public.incidents, public.devices, public.pairing_codes;
