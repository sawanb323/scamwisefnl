-- SCAMWISE core schema
-- Security model:
--   * Identity      : Supabase Auth (phone OTP for app users; email+password+TOTP MFA for admins)
--   * Device binding: each device row is bound to the auth session that registered it
--                     (JWT claim `session_id`). Data access requires an ACTIVE device bound
--                     to the caller's current session. Revoking a device revokes its session.
--   * Writes        : all state changes go through SECURITY DEFINER RPCs or the `analyze`
--                     edge function (service role). Clients have no direct INSERT/UPDATE.
--   * Privacy       : raw message content is never stored. Only scores, indicator codes,
--                     domains and (opt-in) a redacted excerpt.

create extension if not exists pgcrypto with schema extensions;

-- ---------------------------------------------------------------- helpers
create or replace function public.jwt_session_id()
returns uuid language sql stable set search_path = '' as $$
  select nullif(auth.jwt() ->> 'session_id', '')::uuid
$$;

create or replace function public.mask_phone(p text)
returns text language sql immutable set search_path = '' as $$
  select case
    when p is null or length(p) < 6 then null
    else '+' || left(p, greatest(length(p) - 10, 1)) || ' ••••••' || right(p, 4)
  end
$$;

-- ---------------------------------------------------------------- tables
create table public.profiles (
  id               uuid primary key references auth.users(id) on delete cascade,
  phone_masked     text,
  share_with_admin boolean not null default true,   -- incident metadata visible to admins
  share_excerpt    boolean not null default false,  -- store a REDACTED excerpt (off by default)
  notify_high      boolean not null default true,
  notify_medium    boolean not null default false,
  retention_days   int     not null default 30 check (retention_days between 7 and 90),
  created_at       timestamptz not null default now()
);

create type public.device_status as enum ('pending', 'active', 'revoked');

create table public.devices (
  id            uuid primary key default gen_random_uuid(),
  user_id       uuid not null references auth.users(id) on delete cascade,
  install_id    uuid not null,                  -- random id generated by the app install
  session_id    uuid unique,                    -- auth session currently bound to this device
  name          text not null check (length(name) between 1 and 60),
  platform      text check (length(platform) <= 40),
  app_version   text check (length(app_version) <= 20),
  status        public.device_status not null default 'pending',
  is_primary    boolean not null default false,
  created_at    timestamptz not null default now(),
  approved_at   timestamptz,
  approved_by   uuid references public.devices(id) on delete set null,
  revoked_at    timestamptz,
  revoked_reason text,
  last_seen_at  timestamptz,
  unique (user_id, install_id)
);
create index devices_user_idx on public.devices(user_id);

create table public.pairing_codes (
  id                 uuid primary key default gen_random_uuid(),
  user_id            uuid not null references auth.users(id) on delete cascade,
  created_by_device  uuid not null references public.devices(id) on delete cascade,
  status             text not null default 'open'
                     check (status in ('open','claimed','approved','rejected','expired','cancelled')),
  created_at         timestamptz not null default now(),
  expires_at         timestamptz not null,
  claimed_by_device  uuid references public.devices(id) on delete cascade,
  claimed_device_name text,
  claimed_at         timestamptz,
  decided_at         timestamptz
);
create index pairing_codes_user_idx on public.pairing_codes(user_id, status);

-- secret half kept in a table with NO client access at all
create table public.pairing_secrets (
  pairing_id uuid primary key references public.pairing_codes(id) on delete cascade,
  code_hash  text not null unique
);

create table public.pairing_attempts (
  id         bigserial primary key,
  device_id  uuid not null references public.devices(id) on delete cascade,
  ok         boolean not null,
  created_at timestamptz not null default now()
);

create table public.incidents (
  id                   uuid primary key default gen_random_uuid(),
  user_id              uuid not null references auth.users(id) on delete cascade,
  device_id            uuid references public.devices(id) on delete set null,
  device_name          text,
  created_at           timestamptz not null default now(),
  source               text not null default 'paste' check (source in ('share','paste','web')),
  risk_level           text not null check (risk_level in ('high','medium','low','inconclusive')),
  score                int  not null check (score between 0 and 100),
  category             text not null,
  indicators           jsonb not null default '[]'::jsonb,   -- [{code,label,weight,detail}]
  analysis_method      text not null,
  engine_version       text not null,
  ti_status            text not null check (ti_status in ('match','no_match','unavailable','not_configured','not_applicable','error')),
  ti_detail            jsonb,
  url_domains          text[] not null default '{}',
  contained_auth_code  boolean not null default false,
  redacted_excerpt     text check (length(redacted_excerpt) <= 300),
  status               text not null default 'open' check (status in ('open','acknowledged','resolved','false_positive')),
  shared_with_admin    boolean not null default true,
  expires_at           timestamptz not null default now() + interval '30 days'
);
create index incidents_user_idx on public.incidents(user_id, created_at desc);
create index incidents_admin_idx on public.incidents(shared_with_admin, created_at desc);

create table public.alerts (
  id               uuid primary key default gen_random_uuid(),
  user_id          uuid not null references auth.users(id) on delete cascade,
  incident_id      uuid references public.incidents(id) on delete cascade,
  target_device_id uuid not null references public.devices(id) on delete cascade,
  source_device_name text,
  kind             text not null default 'incident' check (kind in ('incident','auth_code','pairing','device')),
  title            text not null,
  body             text not null,
  risk_level       text,
  created_at       timestamptz not null default now(),
  read_at          timestamptz
);
create index alerts_target_idx on public.alerts(target_device_id, created_at desc);

create table public.admin_users (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  note       text,
  created_at timestamptz not null default now()
);

create table public.audit_log (
  id           bigserial primary key,
  at           timestamptz not null default now(),
  actor_id     uuid,
  actor_kind   text not null check (actor_kind in ('admin','user','system')),
  action       text not null,
  target_type  text,
  target_id    text,
  detail       jsonb
);

create table public.feedback (
  id         bigserial primary key,
  created_at timestamptz not null default now(),
  name       text check (length(name) <= 80),
  email      text check (length(email) <= 120),
  kind       text not null default 'feedback' check (kind in ('feedback','demo','business','other')),
  message    text not null check (length(message) between 5 and 2000)
);

